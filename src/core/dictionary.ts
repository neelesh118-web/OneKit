export const DICTIONARY: DictionaryEntry[] = ROWS.map(([word, partOfSpeech, definition]) => ({
  word,
  partOfSpeech,
  definition
}));

const BY_WORD = new Map<string, DictionaryEntry>(DICTIONARY.map((e) => [e.word, e]));

/** Looks up a single word (case-insensitive, hyphen/space removed). */
export function lookupWord(raw: string): DictionaryEntry | null {
  const word = raw.trim().toLowerCase().replace(/[^a-z]/g, "");
  return BY_WORD.get(word) ?? null;
}

/** Extracts the single word from a selection, or null when not one word. */
export function singleWordFromSelection(selectionText: string): string | null {
  const words = selectionText.trim().split(/\s+/).filter(Boolean);
  if (words.length !== 1) return null;
  return words[0] ?? null;
}
